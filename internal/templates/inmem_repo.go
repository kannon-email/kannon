package templates

import (
	"context"
	"slices"
	"strings"
	"sync"
	"time"

	"github.com/kannon-email/kannon/internal/keyset"
	"github.com/kannon-email/kannon/internal/values"
)

// InMemRepository is an in-memory Repository, for the tests of everything above it and for one half
// of the repository specification. Every Template it hands out is a fresh copy, so a caller mutating
// what it was given cannot change what is stored — as with a row read back from Postgres.
type InMemRepository struct {
	mu sync.Mutex
	// templates is kept in insertion order, which is the order the offset listing pages through,
	// as the sqlc-backed Repository pages through the serial id.
	templates []*Template
}

func NewInMemRepository() *InMemRepository {
	return &InMemRepository{}
}

func (r *InMemRepository) Create(_ context.Context, t *Template) error {
	r.mu.Lock()
	defer r.mu.Unlock()

	// No uniqueness check: templates.template_id carries no constraint in Postgres either, and the
	// ID is generated by NewPersistent or NewTransient, so a collision is not a case to model.
	now := time.Now()
	stored := copyTemplate(t)
	stored.createdAt, stored.updatedAt = now, now
	r.templates = append(r.templates, stored)
	*t = *copyTemplate(stored)
	return nil
}

func (r *InMemRepository) Update(_ context.Context, templateID string, fn UpdateFunc) (*Template, error) {
	r.mu.Lock()
	defer r.mu.Unlock()

	i := r.indexOf(templateID)
	if i < 0 {
		return nil, ErrTemplateNotFound
	}
	current := copyTemplate(r.templates[i])
	if err := fn(current); err != nil {
		return nil, err
	}
	// Only what the sqlc-backed Repository writes back is kept: the body and the title.
	stored := r.templates[i]
	stored.html, stored.title, stored.updatedAt = current.Html(), current.Title(), time.Now()
	return copyTemplate(stored), nil
}

func (r *InMemRepository) Delete(_ context.Context, templateID string) (*Template, error) {
	r.mu.Lock()
	defer r.mu.Unlock()

	i := r.indexOf(templateID)
	if i < 0 {
		return nil, ErrTemplateNotFound
	}
	deleted := copyTemplate(r.templates[i])
	r.templates = slices.Delete(r.templates, i, i+1)
	return deleted, nil
}

func (r *InMemRepository) GetByID(_ context.Context, templateID string) (*Template, error) {
	r.mu.Lock()
	defer r.mu.Unlock()

	i := r.indexOf(templateID)
	if i < 0 {
		return nil, ErrTemplateNotFound
	}
	return copyTemplate(r.templates[i]), nil
}

func (r *InMemRepository) FindByDomain(_ context.Context, domain values.DomainName, templateID string) (*Template, error) {
	r.mu.Lock()
	defer r.mu.Unlock()

	i := r.indexOf(templateID)
	if i < 0 || r.templates[i].DomainName() != domain {
		return nil, ErrTemplateNotFound
	}
	return copyTemplate(r.templates[i]), nil
}

func (r *InMemRepository) List(_ context.Context, domain values.DomainName, page Pagination) ([]*Template, error) {
	r.mu.Lock()
	defer r.mu.Unlock()

	persistent := r.persistent(domain)
	start := min(int(page.Skip), len(persistent))
	end := min(start+int(page.Take), len(persistent))
	return persistent[start:end], nil
}

func (r *InMemRepository) ListPage(_ context.Context, domain values.DomainName, page keyset.Page[string]) ([]*Template, error) {
	r.mu.Lock()
	defer r.mu.Unlock()

	persistent := r.persistent(domain)
	slices.SortFunc(persistent, func(a, b *Template) int { return strings.Compare(a.TemplateID(), b.TemplateID()) })
	out := []*Template{}
	for _, t := range persistent {
		if page.After != nil && t.TemplateID() <= *page.After {
			continue
		}
		if len(out) == page.Limit {
			break
		}
		out = append(out, t)
	}
	return out, nil
}

func (r *InMemRepository) Count(_ context.Context, domain values.DomainName) (int, error) {
	r.mu.Lock()
	defer r.mu.Unlock()

	return len(r.persistent(domain)), nil
}

// persistent returns copies of a Domain's Persistent Templates in creation order. The caller holds
// the lock.
func (r *InMemRepository) persistent(domain values.DomainName) []*Template {
	out := []*Template{}
	for _, t := range r.templates {
		if t.DomainName() == domain && t.Type() == TypePersistent {
			out = append(out, copyTemplate(t))
		}
	}
	return out
}

// indexOf returns the position of a Template, or -1. The caller holds the lock.
func (r *InMemRepository) indexOf(templateID string) int {
	return slices.IndexFunc(r.templates, func(t *Template) bool { return t.TemplateID() == templateID })
}

func copyTemplate(t *Template) *Template {
	c := *t
	return &c
}
